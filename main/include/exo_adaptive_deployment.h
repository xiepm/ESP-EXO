#ifndef EXO_ADAPTIVE_DEPLOYMENT_H
#define EXO_ADAPTIVE_DEPLOYMENT_H

/* The regular RS01 mode uses the existing START/STOP contract and a 15 Nm
 * ceiling. Explicit historical bench/trial variants retain their own limits. */
#ifdef ESP_PLATFORM
#include "sdkconfig.h"
#endif
#define EXO_ADAPTIVE_NOMINAL_MAX_MNM 15000U
#define EXO_ADAPTIVE_BENCH_MAX_MNM 500U
#if defined(CONFIG_EXO_ADAPTIVE_ASSIST_MODE) && CONFIG_EXO_ADAPTIVE_ASSIST_MODE
#define EXO_ADAPTIVE_ASSIST_MODE 1
#else
#define EXO_ADAPTIVE_ASSIST_MODE 0
#endif
#if defined(CONFIG_EXO_ADAPTIVE_BOUNDED_TRIAL) && CONFIG_EXO_ADAPTIVE_BOUNDED_TRIAL
#define EXO_ADAPTIVE_TRIAL_ALLOWED 1
#if (defined(CONFIG_EXO_ADAPTIVE_BENCH_ACTIVE) && CONFIG_EXO_ADAPTIVE_BENCH_ACTIVE) || \
    (defined(CONFIG_EXO_ADAPTIVE_NOMINAL_15NM) && CONFIG_EXO_ADAPTIVE_NOMINAL_15NM) || \
    (defined(CONFIG_EXO_ADAPTIVE_ACTIVE_RELEASE) && CONFIG_EXO_ADAPTIVE_ACTIVE_RELEASE) || \
    (defined(CONFIG_EXO_BENCH_PEAK_TEST) && CONFIG_EXO_BENCH_PEAK_TEST) || \
    (defined(CONFIG_EXO_ENGINEERING_GAIT_STIMULUS) && CONFIG_EXO_ENGINEERING_GAIT_STIMULUS)
#error "Bounded manual trial excludes bench, nominal release, peak and trajectory stimulus"
#endif
#else
#define EXO_ADAPTIVE_TRIAL_ALLOWED 0
#endif
#if defined(CONFIG_EXO_ADAPTIVE_ACTIVE_RELEASE) && CONFIG_EXO_ADAPTIVE_ACTIVE_RELEASE
#define EXO_ADAPTIVE_RELEASE_ALLOWED 1
#else
#define EXO_ADAPTIVE_RELEASE_ALLOWED 0
#endif

#if defined(EXO_ADAPTIVE_HOST_ACTIVE_MAX_MNM)
#ifdef ESP_PLATFORM
#error "Host ACTIVE validation is not a deployable ESP configuration"
#endif
#if EXO_ADAPTIVE_HOST_ACTIVE_MAX_MNM <= 0 || EXO_ADAPTIVE_HOST_ACTIVE_MAX_MNM > 15000
#error "Host ACTIVE limit must be in 1..15000 mNm"
#endif
#if EXO_ADAPTIVE_TRIAL_ALLOWED && EXO_ADAPTIVE_HOST_ACTIVE_MAX_MNM != 5000
#error "Trial identity must retain its 5000 mNm ceiling in host validation"
#endif
#define EXO_ADAPTIVE_ACTIVE_ALLOWED 1
#define EXO_ADAPTIVE_CONFIG_MAX_MNM EXO_ADAPTIVE_HOST_ACTIVE_MAX_MNM
#elif EXO_ADAPTIVE_ASSIST_MODE
#define EXO_ADAPTIVE_ACTIVE_ALLOWED 1
#if defined(CONFIG_EXO_MOTOR_RS05) && CONFIG_EXO_MOTOR_RS05
#define EXO_ADAPTIVE_CONFIG_MAX_MNM 5000U
#else
#define EXO_ADAPTIVE_CONFIG_MAX_MNM EXO_ADAPTIVE_NOMINAL_MAX_MNM
#endif
#elif EXO_ADAPTIVE_TRIAL_ALLOWED
#define EXO_ADAPTIVE_ACTIVE_ALLOWED 1
#define EXO_ADAPTIVE_CONFIG_MAX_MNM 5000U
#elif defined(CONFIG_EXO_ADAPTIVE_BENCH_ACTIVE) && CONFIG_EXO_ADAPTIVE_BENCH_ACTIVE
#define EXO_ADAPTIVE_ACTIVE_ALLOWED 1
#if defined(CONFIG_EXO_ADAPTIVE_NOMINAL_15NM) && CONFIG_EXO_ADAPTIVE_NOMINAL_15NM
#define EXO_ADAPTIVE_CONFIG_MAX_MNM EXO_ADAPTIVE_NOMINAL_MAX_MNM
#else
#define EXO_ADAPTIVE_CONFIG_MAX_MNM EXO_ADAPTIVE_BENCH_MAX_MNM
#endif
#else
#define EXO_ADAPTIVE_ACTIVE_ALLOWED 0
#define EXO_ADAPTIVE_CONFIG_MAX_MNM EXO_ADAPTIVE_BENCH_MAX_MNM
#endif
#if EXO_ADAPTIVE_RELEASE_ALLOWED && (!EXO_ADAPTIVE_ACTIVE_ALLOWED || EXO_ADAPTIVE_CONFIG_MAX_MNM != 15000U)
#error "Manual ACTIVE release requires the explicit nominal 15 Nm build"
#endif
#if EXO_ADAPTIVE_RELEASE_ALLOWED && defined(CONFIG_EXO_BENCH_PEAK_TEST) && CONFIG_EXO_BENCH_PEAK_TEST
#error "Manual ACTIVE release must not expose the bench peak test entry"
#endif
#endif
