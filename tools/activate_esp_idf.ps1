<#
.SYNOPSIS
Activates the ESP-IDF v5.5 environment for the current PowerShell session.

.DESCRIPTION
This machine uses the version-specific PowerShell profile generated by the
ESP-IDF Installation Manager (EIM). This wrapper finds and dot-sources that
profile, then validates the commands and paths required by this repository.

Dot-source this script so the environment remains in the caller session:
    . .\tools\activate_esp_idf.ps1
#>

[CmdletBinding()]
param(
    [string]$Version = "v5.5",
    [string]$ToolsRoot
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($ToolsRoot)) {
    if (-not [string]::IsNullOrWhiteSpace($env:IDF_TOOLS_PATH)) {
        $ToolsRoot = $env:IDF_TOOLS_PATH
    } else {
        $ToolsRoot = Join-Path $env:SystemDrive "Espressif\tools"
    }
}

$resolvedToolsRoot = [System.IO.Path]::GetFullPath($ToolsRoot)
$profileName = "Microsoft.$Version.PowerShell_profile.ps1"
$profilePath = Join-Path $resolvedToolsRoot $profileName

if (-not (Test-Path -LiteralPath $profilePath -PathType Leaf)) {
    throw "ESP-IDF EIM activation profile not found: $profilePath. Install or repair $Version with EIM first."
}

# Dot-source the EIM profile so PATH, IDF_PATH and the Python venv are exported
# into the current shell rather than disappearing with a child scope.
. $profilePath

$idfCommand = Get-Command idf.py -ErrorAction SilentlyContinue
if ($null -eq $idfCommand) {
    throw "The ESP-IDF profile ran, but idf.py is unavailable in this session."
}
if ([string]::IsNullOrWhiteSpace($env:IDF_PATH) -or
    -not (Test-Path -LiteralPath $env:IDF_PATH -PathType Container)) {
    throw "The ESP-IDF profile did not export a valid IDF_PATH."
}
if ([string]::IsNullOrWhiteSpace($env:IDF_PYTHON_ENV_PATH) -or
    -not (Test-Path -LiteralPath $env:IDF_PYTHON_ENV_PATH -PathType Container)) {
    throw "The ESP-IDF profile did not export a valid IDF_PYTHON_ENV_PATH."
}

Write-Host "ESP-EXO build environment ready: $(& idf.py --version)"
